set1 = {1, 2, 3, 4, 5}
set2 = {4, 5, 6, 7, 8}

# Union
union = set1 | set2

# Intersection
intersection = set1 & set2

# Difference
difference = set1 - set2

# Symmetric difference
symmetric_difference = set1 ^ set2

print("Union:", union)
print("Intersection:", intersection)
print("Difference:", difference)
print("Symmetric Difference:", symmetric_difference)
