# Start with score
score = 50

# Apply assignment operators one by one and print after each step

score += 10
print("After += 10:", score)

score -= 5
print("After -= 5:", score)

score *= 2
print("After *= 2:", score)

score /= 4
print("After /= 4:", score)

score //= 2
print("After //= 2:", score)

score %= 3
print("After %= 3:", score)

score **= 2
print("After **= 2:", score)